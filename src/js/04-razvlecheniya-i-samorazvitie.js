function funContextTags(){
  const tags = ['дисциплина','тело'];
  if(DB.tasks.some(t=>t.project==='Финансы'||/долг|деньг/i.test(t.title))) tags.push('деньги');
  if(DB.tasks.some(t=>t.project==='Учёба'||/диплом|академ/i.test(t.title))) tags.push('учёба');
  return tags;
}
function pickBook(){
  const ctx = funContextTags();
  const seen = loadJSON('armi_fun_books', []);
  let pool = BOOKS.map(b=>{
    let s = b.tags.filter(t=>ctx.includes(t)).length;
    if(seen.includes(b.id)) s -= 0.6;
    return {b, s: s + Math.random()*0.9};
  }).sort((x,y)=>y.s-x.s);
  const pick = pool[0].b;
  const nx = [...seen.filter(id=>id!==pick.id), pick.id].slice(-5);
  saveJSON('armi_fun_books', nx);
  const reason = 'под твой контекст: ' + ctx.map(c=>({дисциплина:'твой план', тело:'тренировки и восстановление', деньги:'твои финансовые цели', учёба:'учёба и повторение'}[c])).join(' · ');
  return {book:pick, reason};
}

