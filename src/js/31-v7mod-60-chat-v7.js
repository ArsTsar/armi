/* приветственная подсказка над чипами: убираем «счётные» примеры,
   оставляем осмысленные действия — как просил владелец */
(function cleanChatHints(){
  /* сам список чипов патчится в базе; здесь чистим welcome-тексты,
     если они содержат примеры-вычисления */
  const hintsToDrop = /(100 на 5|2\+2×2|2\+2 \+2|сколько будет 2\+2)/gi;
  const origPush = ChatWelcomeText => ChatWelcomeText;
  /* патчим CHATS-заглушки при первом рендере не нужно — тексты чипов
     уже заменены. Дополнительно: фильтр чипов на случай бэкапов со
     старыми настройками */
  const filterChips = list => (list || []).filter(c => !hintsToDrop.test(c));
  window.__armiFilterChips = filterChips;
  /* калькулятор остаётся (он полезен), но в подсказках не рекламируется */
})();

